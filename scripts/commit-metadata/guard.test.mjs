const here = dirname(fileURLToPath(import.meta.url))
const guard = join(here, 'guard.mjs')
const human = { name: 'Jane Human', email: 'jane@example.org' }
const BOT_TRAILER = 'Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>'
const MARKER = 'PRIVATE_MESSAGE_MARKER_d41d8'

test('human identities and human co-authors, including a person named Claude, pass', () => {
  assert.equal(isAutomatedIdentity({ name: 'Claude Dupont', email: 'claude@dupont.example' }), false)
  assert.equal(isAutomatedIdentity({ name: 'Claude', email: 'claude.m@example.org' }), false)
  assert.equal(isAutomatedIdentity({ name: 'dependabot[bot]', email: '49699333+dependabot[bot]@users.noreply.github.com' }), false)
  assert.equal(isAutomatedIdentity({ name: 'GitHub', email: 'noreply@github.com' }), false)
  assert.deepEqual(inspectCommit({ author: human, committer: human, message:
    'docs: explain Claude Code and Codex attribution settings\n\nGenerated files are regenerated by the build.\n\n'
    + 'Co-authored-by: Claude Dupont <claude@dupont.example>\nCo-authored-by: Sam Doe <sam@example.org>\n' }), [])
  for (const line of ['Generated by Claude Dupont', 'Generated with Claude Code is the footer this change removes.',
    'Generated by Claude', 'Generated using Devin Smith\'s script']) {
    assert.deepEqual(inspectCommit({ author: human, committer: human, message: `docs: x\n\n${line}\n` }), [], line)
  }
})

test('automated identities, trailers and signatures are rejected, including CRLF and case variants', () => {
  const cases = [
    [{ author: { name: 'Claude', email: 'noreply@anthropic.com' } }, 'automated author identity'],
    [{ committer: { name: 'Codex', email: 'codex@example.org' } }, 'automated committer identity'],
    [{ author: { name: 'copilot-swe-agent[bot]', email: '198982749+Copilot@users.noreply.github.com' } }, 'automated author identity'],
    [{ message: `fix: x\n\n${BOT_TRAILER}\n` }, 'automated co-authored-by trailer (line 3)'],
    [{ message: 'fix: x\r\n\r\nco-authored-by:claude code <x@example.org>\r\n' }, 'automated co-authored-by trailer (line 3)'],
    [{ message: 'fix: x\n\nCO-AUTHORED-BY: Codex <noreply@openai.com>' }, 'automated co-authored-by trailer (line 3)'],
    [{ message: 'fix: x\n\nSigned-off-by: Claude Sonnet 5 <someone@example.org>' }, 'automated signed-off-by trailer (line 3)'],
    [{ message: 'fix: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)' }, 'automated provenance signature (line 3)'],
    [{ message: 'fix: x\r\rgenerated by ChatGPT' }, 'automated provenance signature (line 3)'],
    [{ message: 'fix: x\n\nGenerated with Claude Code (https://claude.com/claude-code).' }, 'automated provenance signature (line 3)'],
    [{ message: 'fix: x\n\n- Generated using GitHub Copilot' }, 'automated provenance signature (line 3)'],
    [{ message: 'fix: x\n\nClaude-Session: https://claude.ai/code/session_x' }, 'automated session link trailer (line 3)'],
    [{ message: 'Squash (#1)\n\n* Co-authored-by: Claude <noreply@anthropic.com>' }, 'automated co-authored-by trailer (line 3)'],
  ]
  for (const [commit, reason] of cases) {
    assert.deepEqual(inspectCommit({ author: human, committer: human, message: 'x', ...commit }), [reason], JSON.stringify(commit))
  }
})

// ---- real git repositories, hooks, commits and pushes ----
const root = mkdtempSync(join(process.env.COMMIT_METADATA_TEST_TMP || tmpdir(), 'commit-metadata-'))
const baseEnv = Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith('GIT_')))
const env = (identity = human) => ({ ...baseEnv, HOME: root, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1',
  GIT_AUTHOR_NAME: identity.name, GIT_AUTHOR_EMAIL: identity.email, GIT_COMMITTER_NAME: human.name, GIT_COMMITTER_EMAIL: human.email })
const run = (cwd, args, options = {}) => spawnSync(options.command ?? 'git', args, { cwd, encoding: 'utf8', env: options.env ?? env(), input: options.input })
const ok = (cwd, args, options) => {
  const result = run(cwd, args, options)
  assert.equal(result.status, 0, `${args.join(' ')}: ${result.stderr}`)
  return result.stdout.trim()
}
let n = 0
const commit = (cwd, message, { verify = true, identity } = {}) => {
  writeFileSync(join(cwd, `file-${++n}.txt`), `${n}\n`)
  ok(cwd, ['add', '.'])
  const result = run(cwd, ['commit', ...(verify ? [] : ['--no-verify']), '-q', '-F', '-'], { input: message, env: env(identity) })
  return { ...result, sha: result.status === 0 ? ok(cwd, ['rev-parse', 'HEAD']) : undefined }
}
const head = (cwd, ref) => run(cwd, ['rev-parse', '--verify', '-q', ref]).stdout.trim()
const guardRun = (cwd, args, input) => run(cwd, [guard, ...args], { command: process.execPath, input })

const remote = join(root, 'remote.git')
const work = join(root, 'work')
const wt = join(root, 'linked-worktree')
ok(root, ['init', '-q', '--bare', '-b', 'main', remote])
ok(root, ['clone', '-q', remote, work])
ok(work, ['symbolic-ref', 'HEAD', 'refs/heads/main'])
// Protected base history already contains a historical violation (pushed before hooks existed).
commit(work, 'init')
const historical = commit(work, `chore: old\n\n${BOT_TRAILER}\n`).sha
commit(work, 'chore: clean base tip')
ok(work, ['push', '-q', 'origin', 'main'])
const installed = install(work, ['main'])
ok(work, ['worktree', 'add', '-q', '-b', 'feature', wt, 'origin/main'])

test('installer writes the common hook directory, is idempotent and linked worktrees inherit it', () => {
  assert.equal(installed.written.length, 3)
  assert.equal(install(work, ['main']).written.length, 0)
  assert.equal(ok(wt, ['rev-parse', '--path-format=absolute', '--git-path', 'hooks']), installed.hooks)
  assert.match(readFileSync(join(installed.hooks, 'pre-push'), 'utf8'), /pre-push --base main -- "\$@"/)
  assert.match(hookFiles(['dev', 'main'])['pre-push'], /pre-push --base dev --base main -- "\$@"/)
  assert.equal(readFileSync(join(installed.hooks, 'commit-metadata-guard.mjs'), 'utf8'), readFileSync(guard, 'utf8'))
})

test('installer refuses existing hooks and core.hooksPath without overwriting', () => {
  const other = join(root, 'other')
  ok(root, ['init', '-q', other])
  writeFileSync(join(other, '.git/hooks/pre-push'), '#!/bin/sh\nexit 0\n')
  assert.throws(() => install(other, ['main']), /refusing to overwrite/)
  assert.equal(readFileSync(join(other, '.git/hooks/pre-push'), 'utf8'), '#!/bin/sh\nexit 0\n')
  const configured = join(root, 'configured')
  ok(root, ['init', '-q', configured])
  ok(configured, ['config', 'core.hooksPath', 'custom-hooks'])
  assert.throws(() => install(configured, ['main']), /core\.hooksPath is set/)
  assert.throws(() => install(work, ['-main']), /invalid --base/)
})

test('installer refuses when another linked worktree overrides core.hooksPath', () => {
  const primary = join(root, 'wtconfig')
  const linked = join(root, 'wtconfig-linked')
  ok(root, ['init', '-q', '-b', 'main', primary])
  commit(primary, 'init', { verify: false })
  ok(primary, ['worktree', 'add', '-q', '-b', 'other', linked])
  ok(primary, ['config', 'extensions.worktreeConfig', 'true'])
  ok(linked, ['config', '--worktree', 'core.hooksPath', join(root, 'elsewhere-hooks')])
  assert.throws(() => install(primary, ['main']), /core\.hooksPath is set/)
  assert.equal(existsSync(join(primary, '.git/hooks/pre-push')), false)
  assert.equal(existsSync(join(primary, '.git/hooks/commit-metadata-guard.mjs')), false)
})

test('reinstall restores the executable mode of identical hooks and Git runs them again', () => {
  chmodSync(join(installed.hooks, 'commit-msg'), 0o644)
  chmodSync(join(installed.hooks, 'pre-push'), 0o644)
  const again = install(work, ['main'])
  assert.deepEqual(again.repaired.sort(), [join(installed.hooks, 'commit-msg'), join(installed.hooks, 'pre-push')])
  for (const name of ['commit-msg', 'pre-push', 'commit-metadata-guard.mjs']) {
    assert.equal(statSync(join(installed.hooks, name)).mode & 0o777, 0o755, name)
  }
  const result = commit(wt, `feat: bad\n\n${BOT_TRAILER}\n`)
  assert.notEqual(result.status, 0)
  assert.match(result.stderr, /automated co-authored-by trailer/)
  ok(wt, ['reset', '-q', '--hard'])
})

test('commit-msg hook allows human commits and rejects automated attribution in a linked worktree', () => {
  assert.equal(commit(wt, 'feat: clean\n\nCo-authored-by: Claude Dupont <claude@dupont.example>\n').status, 0)
  for (const message of [`feat: bad\n\n${BOT_TRAILER}\n`, 'feat: bad\r\n\r\nco-authored-by: Codex <noreply@openai.com>\r\n',
    'feat: bad\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n']) {
    const result = commit(wt, `${message}\n${MARKER}\n`)
    assert.notEqual(result.status, 0)
    assert.match(result.stderr, /commit-metadata: new commit: automated/)
    assert.doesNotMatch(result.stderr, new RegExp(MARKER))
  }
  const bot = commit(wt, 'feat: identity', { identity: { name: 'Claude', email: 'noreply@anthropic.com' } })
  assert.notEqual(bot.status, 0)
  assert.match(bot.stderr, /automated author identity/)
  ok(wt, ['reset', '-q', '--hard'])
})

test('pre-push accepts a clean branch over a base with historical violations', () => {
  ok(wt, ['push', '-q', 'origin', 'feature'])
  assert.equal(head(work, 'refs/remotes/origin/feature'), head(wt, 'HEAD'))
  const range = guardRun(wt, ['range', '--base', 'origin/main', '--head', 'HEAD'])
  assert.equal(range.status, 0, range.stderr)
  assert.equal(guardRun(wt, ['range', '--base', 'origin/main', '--head', historical]).status, 0)
})

test('intermediate violation followed by a clean head is rejected by pre-push and range', () => {
  ok(wt, ['checkout', '-q', '-b', 'intermediate', 'origin/main'])
  const bad = commit(wt, `feat: bad\n\n${BOT_TRAILER}\n${MARKER}\n`, { verify: false }).sha
  assert.equal(commit(wt, 'feat: clean head').status, 0)
  const push = run(wt, ['push', 'origin', 'intermediate'])
  assert.notEqual(push.status, 0)
  assert.match(push.stderr, new RegExp(`${bad}: automated co-authored-by trailer`))
  assert.doesNotMatch(push.stderr, new RegExp(MARKER))
  assert.equal(head(work, 'refs/remotes/origin/intermediate'), '')
  const range = guardRun(wt, ['range', '--base', 'origin/main', '--head', 'HEAD'])
  assert.equal(range.status, 1)
  assert.match(range.stderr, new RegExp(bad))
})

test('clean merge commit importing a bad ancestor is rejected', () => {
  ok(wt, ['checkout', '-q', '-b', 'side', 'origin/main'])
  const bad = commit(wt, 'feat: side\n\nGenerated by Codex\n', { verify: false }).sha
  ok(wt, ['checkout', '-q', '-b', 'merged', 'origin/main'])
  assert.equal(commit(wt, 'feat: topic').status, 0)
  ok(wt, ['merge', '-q', '--no-ff', '-m', 'Merge branch side', 'side'])
  const push = run(wt, ['push', 'origin', 'merged'])
  assert.notEqual(push.status, 0)
  assert.match(push.stderr, new RegExp(`${bad}: automated provenance signature`))
  assert.equal(guardRun(wt, ['range', '--base', 'origin/main', '--head', 'merged']).status, 1)
})

test('already-pushed violations, new branches with imported ancestors, and deletions', () => {
  ok(wt, ['checkout', '-q', '-b', 'legacy', 'origin/main'])
  const bad = commit(wt, 'feat: legacy', { verify: false, identity: { name: 'Claude Code', email: 'x@example.org' } }).sha
  ok(wt, ['push', '-q', '--no-verify', 'origin', 'legacy'])
  assert.equal(commit(wt, 'feat: clean follow-up').status, 0)
  const again = run(wt, ['push', 'origin', 'legacy'])
  assert.notEqual(again.status, 0, 'old remote head must not hide an already-pushed violation')
  assert.match(again.stderr, new RegExp(`${bad}: automated author identity`))
  ok(wt, ['checkout', '-q', '-b', 'imported', bad])
  assert.equal(commit(wt, 'feat: new branch').status, 0)
  const fresh = run(wt, ['push', 'origin', 'imported:refs/heads/brand-new'])
  assert.notEqual(fresh.status, 0)
  assert.match(fresh.stderr, new RegExp(bad))
  ok(wt, ['push', '-q', 'origin', '--delete', 'legacy'])
  assert.equal(head(work, 'refs/remotes/origin/legacy'), '')
})

test('with dev and main bases, pre-push checks against the one declared or destination target', () => {
  const promoRemote = join(root, 'promo-remote.git')
  const clone = join(root, 'promo-work')
  ok(root, ['init', '-q', '--bare', '-b', 'main', promoRemote])
  ok(root, ['clone', '-q', promoRemote, clone])
  ok(clone, ['symbolic-ref', 'HEAD', 'refs/heads/main'])
  commit(clone, 'init')
  ok(clone, ['push', '-q', 'origin', 'main'])
  ok(clone, ['checkout', '-q', '-b', 'dev'])
  // Already pushed to dev before hooks existed; not yet on main.
  const bad = commit(clone, `feat: dev-only\n\n${BOT_TRAILER}\n`).sha
  ok(clone, ['push', '-q', 'origin', 'dev'])
  assert.equal(install(clone, ['dev', 'main']).written.length, 3)
  // B: a clean feature for dev is not rejected because dev already contains bad.
  ok(clone, ['checkout', '-q', '-b', 'feature-c', 'origin/dev'])
  assert.equal(commit(clone, 'feat: clean C').status, 0)
  const undeclared = run(clone, ['push', 'origin', 'feature-c'])
  assert.notEqual(undeclared.status, 0, 'an undeclared target must fail closed, not silently use dev')
  assert.match(undeclared.stderr, /git config branch\.feature-c\.commitMetadataBase <dev\|main>/)
  assert.equal(head(clone, 'refs/remotes/origin/feature-c'), '')
  ok(clone, ['config', 'branch.feature-c.commitMetadataBase', 'dev'])
  ok(clone, ['push', '-q', 'origin', 'feature-c'])
  // A: a promotion toward main is checked against main, so dev cannot hide bad.
  ok(clone, ['checkout', '-q', '-b', 'promotion', 'origin/dev'])
  assert.equal(commit(clone, 'chore: clean promotion tip').status, 0)
  ok(clone, ['config', 'branch.promotion.commitMetadataBase', 'main'])
  const push = run(clone, ['push', 'origin', 'promotion'])
  assert.notEqual(push.status, 0)
  assert.match(push.stderr, new RegExp(`${bad}: automated co-authored-by trailer`))
  assert.equal(head(clone, 'refs/remotes/origin/promotion'), '')
  // Exact protected destinations select themselves; conflicts and invalid targets fail closed.
  const toMain = run(clone, ['push', 'origin', 'feature-c:refs/heads/main'])
  assert.notEqual(toMain.status, 0)
  assert.match(toMain.stderr, /conflicting/)
  const direct = run(clone, ['push', 'origin', 'HEAD:refs/heads/main'])
  assert.notEqual(direct.status, 0)
  assert.match(direct.stderr, new RegExp(`${bad}: automated co-authored-by trailer`))
  ok(clone, ['config', 'branch.promotion.commitMetadataBase', 'staging'])
  assert.match(run(clone, ['push', 'origin', 'promotion']).stderr, /fail closed/)
  ok(clone, ['config', '--add', 'branch.promotion.commitMetadataBase', 'main'])
  assert.match(run(clone, ['push', 'origin', 'promotion']).stderr, /fail closed/)
  assert.equal(head(clone, 'refs/remotes/origin/promotion'), '')
  // CI range stays single-target.
  assert.equal(guardRun(clone, ['range', '--base', 'origin/dev', '--head', 'promotion']).status, 0)
  assert.equal(guardRun(clone, ['range', '--base', 'origin/main', '--head', 'promotion']).status, 1)
  ok(clone, ['checkout', '-q', '-b', 'from-main', 'origin/main'])
  assert.equal(commit(clone, 'feat: clean').status, 0)
  ok(clone, ['config', 'branch.from-main.commitMetadataBase', 'main'])
  ok(clone, ['push', '-q', 'origin', 'from-main'])
})

test('missing or unresolvable refs and unnamed remotes fail closed', () => {
  const zero = '0'.repeat(40)
  const tip = head(wt, 'feature')
  const line = `refs/heads/feature ${tip} refs/heads/feature ${zero}\n`
  const missingBase = guardRun(wt, ['pre-push', '--base', 'no-such-branch', '--', 'origin', remote], line)
  assert.equal(missingBase.status, 2)
  assert.match(missingBase.stderr, /fail closed/)
  const toMissingDev = `refs/heads/feature ${tip} refs/heads/dev ${zero}\n`
  assert.equal(guardRun(wt, ['pre-push', '--base', 'main', '--base', 'dev', '--', 'origin', remote], toMissingDev).status, 2)
  assert.equal(guardRun(wt, ['pre-push', '--base', 'main', '--base', 'dev', '--', 'origin', remote], line).status, 2)
  assert.equal(guardRun(wt, ['pre-push', '--base', 'main', '--', 'origin', remote], line).status, 0)
  assert.equal(guardRun(wt, ['pre-push', '--base', 'main', '--', remote, remote], line).status, 2)
  assert.equal(guardRun(wt, ['pre-push', '--base', 'main', '--', 'origin', remote], 'garbage\n').status, 2)
  assert.equal(guardRun(wt, ['range', '--base', 'origin/main', '--head', 'deadbeef']).status, 2)
  assert.equal(guardRun(wt, ['range', '--base', 'origin/nope', '--head', 'HEAD']).status, 2)
  assert.equal(guardRun(wt, ['range', '--head', 'HEAD']).status, 2)
  const urlPush = run(wt, ['push', remote, 'feature:refs/heads/by-url'])
  assert.notEqual(urlPush.status, 0)
  assert.equal(guardRun(wt, ['pre-push', '--base', 'main', '--', 'origin', remote], `(delete) ${zero} refs/heads/x ${tip}\n`).status, 0)
})
