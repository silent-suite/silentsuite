#!/usr/bin/env python3
"""Build, render and package the SilentSuite Dokploy blueprint. Standard library only.

  template [--check]   print (or verify) template.toml, generated from the Umbrel package files
  render OUT [...]     lay out OUT/code/docker-compose.yml, OUT/code/.env and OUT/files/** the way
                       Dokploy v0.31.4 does for a compose service created from the template
  import               print the base64 "Import" payload the Dokploy template site produces

The renderer ports Dokploy's processTemplate for the helpers this blueprint uses (domain, hash:N)
and refuses every other helper. Secrets are written only to the private .env file, never printed.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import re
import secrets
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BLUEPRINT = ROOT / "self-host/dokploy/silentsuite"
UMBREL_DATA = ROOT / "self-host/umbrel/silentsuite/data"

# Mount file path in Dokploy -> (Umbrel source, exact string replacements). Nothing else changes.
MOUNTS = {
    "/silentsuite/router.conf": (
        UMBREL_DATA / "router/default.conf",
        (
            ("http://silentsuite_server_1:3735;", "http://silentsuite-server:3735;"),
            ("http://silentsuite_web_1:3000;", "http://silentsuite-web:3000;"),
        ),
    ),
    "/silentsuite/init.sh": (
        UMBREL_DATA / "bootstrap/init.sh",
        (
            ("# One-shot, network-less preparation", "# One-shot preparation"),
            ("host = silentsuite_postgres_1\n", "host = silentsuite-postgres\n"),
        ),
    ),
    "/silentsuite/server-start.sh": (UMBREL_DATA / "bootstrap/server-start.sh", ()),
}

HEADER = """\
# SilentSuite for Dokploy. Generated by scripts/dokploy-template-render.py in the
# silent-suite/silentsuite repository from its Umbrel package files; edit those, then regenerate.
#
# Before the first signup, open Domains, switch the domain to HTTPS (your own domain or the
# generated one, with Let's Encrypt) and redeploy. The installation password the owner enters
# at signup is SILENTSUITE_INSTALLATION_PASSWORD in the Environment tab.

[variables]
main_domain = "${domain}"
installation_password = "${hash:32}"
registration_signing = "${hash:64}"
db_password = "${hash:64}"

[config]
env = [
  "SILENTSUITE_INSTALLATION_PASSWORD=${installation_password}",
  "SILENTSUITE_REGISTRATION_SIGNING=${registration_signing}",
  "SILENTSUITE_DB_PASSWORD=${db_password}",
]

[[config.domains]]
serviceName = "silentsuite"
port = 8080
host = "${main_domain}"
"""

SECRET_ENV = (
    "SILENTSUITE_INSTALLATION_PASSWORD",
    "SILENTSUITE_REGISTRATION_SIGNING",
    "SILENTSUITE_DB_PASSWORD",
)
# Dokploy helper names; any ${...} in mount content whose name is one of these, starts with one
# of the prefixes, or is a template variable would be rewritten by Dokploy.
HELPERS = {"domain", "base64", "password", "hash", "uuid", "timestamp", "timestampms",
           "timestamps", "randomPort", "jwt", "username", "email"}
HELPER_PREFIXES = ("base64:", "password:", "hash:", "jwt:", "timestamps:", "timestampms:")
PLACEHOLDER = re.compile(r"\$\{([^}]+)\}")


class RenderError(Exception):
    pass


def mount_content(file_path: str) -> str:
    source, replacements = MOUNTS[file_path]
    text = source.read_text(encoding="utf-8")
    for old, new in replacements:
        if text.count(old) != 1:
            raise RenderError(f"{source.name}: expected exactly one occurrence of a replaced string")
        text = text.replace(old, new)
    if "'''" in text:
        raise RenderError(f"{source.name}: cannot be a TOML literal string")
    return text


def build_template() -> str:
    parts = [HEADER]
    for file_path in MOUNTS:
        parts.append(f"\n[[config.mounts]]\nfilePath = \"{file_path}\"\ncontent = '''\n{mount_content(file_path)}'''\n")
    return "".join(parts)


def dokploy_name(name: str, variables: dict) -> bool:
    return name in HELPERS or name.startswith(HELPER_PREFIXES) or name in variables


def process_value(value: str, variables: dict, host: str) -> str:
    """Port of Dokploy processValue for this blueprint: two passes, unknown names kept."""

    def first(match):
        name = match.group(1)
        if name == "domain":
            return host
        if name in HELPERS or name.startswith(HELPER_PREFIXES):
            raise RenderError(f"helper not supported by this renderer: {name.split(':')[0]}")
        return variables.get(name, match.group(0))

    value = PLACEHOLDER.sub(first, value)
    return PLACEHOLDER.sub(lambda m: variables.get(m.group(1), m.group(0)), value)


def process_variables(template: dict, host: str) -> dict:
    variables = {}
    for key, value in template.get("variables", {}).items():
        if value == "${domain}":
            variables[key] = host
        elif (match := re.fullmatch(r"\$\{hash:(\d+)\}", value)):
            length = int(match.group(1))
            variables[key] = secrets.token_hex((length + 1) // 2)[:length]
        elif value.startswith("${"):
            raise RenderError(f"variable helper not supported by this renderer: {key}")
        else:
            variables[key] = value
    for key, value in list(variables.items()):
        variables[key] = process_value(value, variables, host)
    return variables


def load_template() -> dict:
    return tomllib.loads((BLUEPRINT / "template.toml").read_text(encoding="utf-8"))


def isolate(compose_text: str, app_name: str, volumes: bool) -> str:
    """Dokploy isolatedDeployment: every service joins the external app network (and,
    with isolatedDeploymentsVolume, named volumes get the app-name suffix)."""
    import yaml  # hash-locked in CI

    compose = yaml.safe_load(compose_text)
    compose.setdefault("networks", {})[app_name] = {"name": app_name, "external": True}
    for service in compose["services"].values():
        networks = service.get("networks")
        if networks is None:
            service["networks"] = [app_name]
        elif isinstance(networks, list):
            networks.append(app_name)
        else:
            networks[app_name] = {}
        if volumes:
            for index, volume in enumerate(service.get("volumes", [])):
                name, _, rest = volume.partition(":")
                if name in compose.get("volumes", {}):
                    service["volumes"][index] = f"{name}-{app_name}:{rest}"
    if volumes:
        compose["volumes"] = {f"{name}-{app_name}": spec for name, spec in compose["volumes"].items()}
    return yaml.safe_dump(compose, sort_keys=False)


def shared_network(compose_text: str) -> str:
    """Dokploy non-isolated deployment: the domain service also joins dokploy-network."""
    import yaml  # hash-locked in CI

    compose = yaml.safe_load(compose_text)
    domains = {domain["serviceName"] for domain in load_template()["config"]["domains"]}
    for name in domains:
        service = compose["services"][name]
        service["networks"] = ["default", "dokploy-network"]
    compose.setdefault("networks", {})["dokploy-network"] = {"external": True}
    return yaml.safe_dump(compose, sort_keys=False)


def render(args) -> None:
    out = args.out
    if out.exists():
        raise RenderError("render output must not exist yet")
    template = load_template()
    variables = process_variables(template, args.host)
    variables = {"APP_NAME": args.app_name, **variables}
    env_lines = [process_value(line, variables, args.host) for line in template["config"]["env"]]
    env = dict(line.split("=", 1) for line in env_lines)
    if args.carry_from:
        earlier = dict(
            line.split("=", 1)
            for line in args.carry_from.read_text(encoding="utf-8").splitlines() if "=" in line
        )
        for name in SECRET_ENV:
            env[name] = earlier[name]
    for name in args.empty or []:
        env[name] = ""
    for name in args.omit or []:
        env.pop(name, None)

    compose_text = (BLUEPRINT / "docker-compose.yml").read_text(encoding="utf-8")
    for old, new in args.image or []:
        if compose_text.count(f"image: {old}\n") < 1:
            raise RenderError("image to replace is not pinned in the blueprint")
        compose_text = compose_text.replace(f"image: {old}\n", f"image: {new}\n")
    if args.isolated:
        compose_text = isolate(compose_text, args.app_name, args.isolated_volumes)
    else:
        compose_text = shared_network(compose_text)

    (out / "code").mkdir(parents=True)
    (out / "code/docker-compose.yml").write_text(compose_text, encoding="utf-8")
    descriptor = os.open(out / "code/.env", os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write("".join(f"{key}={value}\n" for key, value in env.items()))
    for mount in template["config"]["mounts"]:
        relative = process_value(mount["filePath"], variables, args.host).lstrip("/")
        target = out / "files" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(process_value(mount["content"], variables, args.host), encoding="utf-8")


def import_payload() -> str:
    document = {
        "compose": (BLUEPRINT / "docker-compose.yml").read_text(encoding="utf-8"),
        "config": (BLUEPRINT / "template.toml").read_text(encoding="utf-8"),
    }
    return base64.b64encode(json.dumps(document, indent=2).encode("utf-8")).decode("ascii")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    template = commands.add_parser("template")
    template.add_argument("--check", action="store_true")
    rendering = commands.add_parser("render")
    rendering.add_argument("out", type=Path)
    rendering.add_argument("--host", default="silentsuite.ci.test")
    rendering.add_argument("--app-name", default="silentsuite-ci")
    rendering.add_argument("--isolated", action="store_true")
    rendering.add_argument("--isolated-volumes", action="store_true")
    rendering.add_argument("--image", nargs=2, action="append", metavar=("OLD", "NEW"))
    rendering.add_argument("--carry-from", type=Path, metavar="ENV_FILE",
                           help="reuse the three secrets of an earlier render (restore tests)")
    rendering.add_argument("--empty", action="append", choices=SECRET_ENV)
    rendering.add_argument("--omit", action="append", choices=SECRET_ENV)
    commands.add_parser("import")
    args = parser.parse_args()
    try:
        if args.command == "template":
            expected = build_template()
            if args.check:
                actual = (BLUEPRINT / "template.toml").read_text(encoding="utf-8")
                if actual != expected:
                    raise RenderError("template.toml differs from its Umbrel sources; regenerate it")
            else:
                sys.stdout.write(expected)
        elif args.command == "render":
            render(args)
        else:
            print(import_payload())
    except (RenderError, OSError, KeyError, ValueError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
